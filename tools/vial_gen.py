#!/usr/bin/env python3
"""Emit the C data the Vial protocol serves for the keyboard.

usage: vial_gen.py VIAL_JSON UID UNLOCK_KEYS

  VIAL_JSON    the Vial keyboard definition (name, matrix size, layout, custom keycodes)
  UID          the 8-byte keyboard id, 16 hex digits (0x prefix allowed)
  UNLOCK_KEYS  the keys to hold to unlock, "row,col;row,col" (1 to 14 of them)

The definition goes out minified and LZMA-compressed (the xz container), which is what the Vial app expects, and is served in
32-byte pages (core/vial.c). The C file is written to the standard output.
"""

import json
import lzma
import os
import sys


def c_bytes(data):
    return ", ".join("0x{:02X}".format(b) for b in data)


def main():
    if len(sys.argv) != 4:
        print(__doc__, file=sys.stderr)
        return 1

    json_path, uid_text, unlock_text = sys.argv[1:]

    with open(json_path, "r") as f:
        definition = json.dumps(json.load(f), separators=(",", ":"))
    compressed = lzma.compress(definition.encode("utf-8"))

    uid = bytes.fromhex(uid_text.removeprefix("0x").removeprefix("0X"))
    if len(uid) != 8:
        print("vial_gen: the keyboard id must be 8 bytes", file=sys.stderr)
        return 1

    keys = [tuple(int(n) for n in pair.split(",")) for pair in unlock_text.split(";") if pair.strip()]
    if not 1 <= len(keys) <= 14:
        print("vial_gen: between 1 and 14 unlock keys are needed", file=sys.stderr)
        return 1

    print("// Generated by tools/vial_gen.py from {}: do not edit.".format(os.path.basename(json_path)))
    print('#include "vial.h"')
    print()
    print("const ROM uint8_t vial_definition[] = {{{}}};".format(c_bytes(compressed)))
    print("const uint32_t vial_definition_size = {}u;".format(len(compressed)))
    print("const ROM uint8_t vial_keyboard_uid[8] = {{{}}};".format(c_bytes(uid)))
    print("const ROM uint8_t vial_unlock_keys[][2] = {{{}}};".format(", ".join("{{{}, {}}}".format(r, c) for r, c in keys)))
    print("const uint8_t vial_unlock_key_count = {};".format(len(keys)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
